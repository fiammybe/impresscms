#!/usr/bin/env php
<?php
/**
 * Finds hardcoded HTML markup in PHP string literals / inline HTML of the ICMS library.
 *
 * Usage:
 *   php bin/find-hardcoded-html.php [--format=text|markdown|baseline] [--check=baseline-file] [path ...]
 *
 * --format=baseline   prints "relative/file.php<TAB>count" lines (count of strings with markup)
 * --check=FILE        exits 1 when a file has more markup strings than recorded in FILE
 *
 * Only string tokens are inspected (comments and docblocks are ignored).
 */
$root = dirname(__DIR__);
$format = 'text';
$check = null;
$paths = array();
foreach (array_slice($argv, 1) as $arg) {
	if (strpos($arg, '--format=') === 0) {
		$format = substr($arg, 9);
	} elseif (strpos($arg, '--check=') === 0) {
		$check = substr($arg, 8);
	} else {
		$paths[] = realpath($arg) ?: $arg;
	}
}

$tags = 'div|table|thead|tbody|tfoot|tr|td|th|form|input|select|option|optgroup|textarea|a|span|ul|ol|li|img|p|br|hr|h[1-6]|script|style|label|button|iframe|fieldset|legend|b|i|strong|em|small|center|font|link|meta|dl|dt|dd|pre|code|body|html|head|title';
$re = '#<(/?)(' . $tags . ')(\s[^<>]*)?/?>#i';

function currentFunction(array $tokens, $i) {
	$depthStack = array();
	$name = '';
	$class = '';
	for ($j = 0; $j <= $i; $j++) {
		$t = $tokens[$j];
		if (is_array($t) && in_array($t[0], array(T_CLASS, T_INTERFACE, T_TRAIT), true)) {
			for ($k = $j + 1; $k < count($tokens); $k++) {
				if (is_array($tokens[$k]) && $tokens[$k][0] === T_STRING) {
					$class = $tokens[$k][1];
					break;
				}
			}
		}
		if (is_array($t) && $t[0] === T_FUNCTION) {
			for ($k = $j + 1; $k < count($tokens); $k++) {
				if (is_array($tokens[$k]) && $tokens[$k][0] === T_STRING) {
					$name = $tokens[$k][1];
					break;
				}
				if ($tokens[$k] === '(') {
					break;
				}
			}
		}
	}
	return ($class ? $class . '::' : '') . ($name ?: '(top)');
}

if (!$paths) {
	$paths[] = $root . '/htdocs/libraries/icms';
}
$files = array();
foreach ($paths as $path) {
	if (is_file($path)) {
		$files[] = $path;
		continue;
	}
	$it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($path, FilesystemIterator::SKIP_DOTS));
	foreach ($it as $f) {
		if ($f->isFile() && substr($f->getFilename(), -4) === '.php') {
			$files[] = $f->getPathname();
		}
	}
}
sort($files);

$results = array();
foreach ($files as $file) {
	$src = file_get_contents($file);
	$tokens = token_get_all($src);
	$hits = array();
	$n = count($tokens);
	for ($i = 0; $i < $n; $i++) {
		$t = $tokens[$i];
		if (!is_array($t)) {
			continue;
		}
		if (!in_array($t[0], array(T_CONSTANT_ENCAPSED_STRING, T_ENCAPSED_AND_WHITESPACE, T_INLINE_HTML), true)) {
			continue;
		}
		if ($t[0] === T_INLINE_HTML && trim($t[1]) === '') {
			continue;
		}
		if (preg_match_all($re, $t[1], $m)) {
			$hits[] = array(
				'line' => $t[2],
				'func' => currentFunction($tokens, $i),
				'tags' => count($m[0]),
				'snippet' => trim(preg_replace('/\s+/', ' ', substr($t[1], 0, 90))),
			);
		}
	}
	if ($hits) {
		$rel = ltrim(str_replace($root, '', $file), '/');
		$results[$rel] = $hits;
	}
}

if ($check !== null) {
	$base = array();
	foreach (file($check, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES) as $line) {
		if ($line[0] === '#') {
			continue;
		}
		list($f, $c) = explode("\t", $line);
		$base[$f] = (int)$c;
	}
	$fail = 0;
	foreach ($results as $f => $h) {
		$allowed = isset($base[$f]) ? $base[$f] : 0;
		if (count($h) > $allowed) {
			fwrite(STDERR, "NEW hardcoded HTML: $f has " . count($h) . " markup strings (baseline $allowed)\n");
			$fail = 1;
		}
	}
	exit($fail);
}

if ($format === 'baseline') {
	echo "# file<TAB>number of string literals containing HTML markup (accepted baseline)\n";
	foreach ($results as $f => $h) {
		echo $f . "\t" . count($h) . "\n";
	}
	exit(0);
}

if ($format === 'markdown') {
	$totalTags = 0;
	foreach ($results as $h) {
		foreach ($h as $x) {
			$totalTags += $x['tags'];
		}
	}
	echo "# Hardcoded HTML inventory\n\nGenerated by `php bin/find-hardcoded-html.php --format=markdown`.\n\n";
	echo count($results) . " files, $totalTags tags.\n\n| Strings | Tags | File |\n|---|---|---|\n";
	uasort($results, function ($a, $b) {
		return array_sum(array_column($b, 'tags')) - array_sum(array_column($a, 'tags'));
	});
	foreach ($results as $f => $h) {
		echo "| " . count($h) . " | " . array_sum(array_column($h, 'tags')) . " | `" . str_replace('htdocs/libraries/icms/', '', $f) . "` |\n";
	}
	echo "\n## Detail\n";
	foreach ($results as $f => $h) {
		echo "\n### `" . str_replace('htdocs/libraries/icms/', '', $f) . "`\n";
		foreach ($h as $x) {
			echo "- L{$x['line']} `{$x['func']}` ({$x['tags']} tags): `" . str_replace('`', "'", $x['snippet']) . "`\n";
		}
	}
	exit(0);
}

foreach ($results as $f => $h) {
	foreach ($h as $x) {
		echo "$f:{$x['line']}\t{$x['func']}\t{$x['tags']}\t{$x['snippet']}\n";
	}
}
