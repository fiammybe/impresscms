<?php

declare(strict_types=1);

namespace App\Ipf\Schema;

use LogicException;

/**
 * A Laravel migration that expands a legacy table with the additive
 * differences of its schema contract: new columns typed as
 * Icms\Db\Legacy\Updater\Handler would type them (NOT NULL, its defaults), and
 * missing join tables of explicit relations.
 *
 * It never drops, renames or alters an existing column; down() removes only
 * what up() added. Migrations run with `php artisan migrate`, never during a
 * web request. Contracting a table is a later, hand-written migration, once no
 * legacy code uses what it removes.
 */
final class MigrationGenerator
{
    /**
     * @param list<SchemaDifference> $differences
     */
    public function generate(string $table, array $differences): string
    {
        $additive = array_values(array_filter($differences, static fn (SchemaDifference $difference): bool => $difference->kind === SchemaDifference::ADDITIVE));
        if ($additive === []) {
            throw new LogicException("{$table} has no additive differences.");
        }

        $up = [];
        $down = [];
        $columns = [];
        foreach ($additive as $difference) {
            if (isset($difference->column['joinTable'])) {
                $join = var_export((string) $difference->column['joinTable'], true);
                $up[] = "        Schema::connection('icms')->create({$join}, static function (Blueprint \$table): void {\n"
                    . "            \$table->integer('source_id');\n"
                    . "            \$table->integer('target_id');\n"
                    . "            \$table->primary(['source_id', 'target_id']);\n"
                    . "        });";
                $down[] = "        Schema::connection('icms')->dropIfExists({$join});";

                continue;
            }

            $columns[] = $difference->column;
        }

        if ($columns !== []) {
            $name = var_export($table, true);
            $lines = array_map(static fn (array $column): string => '            ' . self::column($column) . ';', $columns);
            $up[] = "        Schema::connection('icms')->table({$name}, static function (Blueprint \$table): void {\n" . implode("\n", $lines) . "\n        });";
            $dropped = implode(', ', array_map(static fn (array $column): string => var_export((string) $column['name'], true), $columns));
            $down[] = "        Schema::connection('icms')->table({$name}, static function (Blueprint \$table): void {\n            \$table->dropColumn([{$dropped}]);\n        });";
        }

        $upCode = implode("\n\n", $up);
        $downCode = implode("\n\n", array_reverse($down));

        return <<<PHP
            <?php

            declare(strict_types=1);

            use Illuminate\\Database\\Migrations\\Migration;
            use Illuminate\\Database\\Schema\\Blueprint;
            use Illuminate\\Support\\Facades\\Schema;

            /*
             * Generated by `php artisan icms:schema:diff --migration`: expands {$table}
             * for its IPF definition. Additive only; legacy code keeps working with
             * the table before and after.
             */
            return new class extends Migration
            {
                public function up(): void
                {
            {$upCode}
                }

                public function down(): void
                {
            {$downCode}
                }
            };

            PHP;
    }

    /**
     * @param array<string, mixed> $column
     */
    private static function column(array $column): string
    {
        $name = var_export((string) $column['name'], true);
        $default = $column['default'] ?? null;

        return match ($column['family']) {
            'varchar' => "\$table->string({$name}, 255)->default(" . var_export((string) $default, true) . ')',
            'text' => "\$table->text({$name})",
            'int' => "\$table->integer({$name})->default(" . (int) $default . ')',
            'float' => "\$table->float({$name})->default(" . (float) $default . ')',
            default => throw new LogicException("Unknown column family {$column['family']}."),
        };
    }
}
